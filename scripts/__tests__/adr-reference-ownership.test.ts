import { afterEach, expect, test } from "bun:test";
import { mkdir, readFile, rm, symlink } from "node:fs/promises";
import { join, resolve } from "node:path";

import { buildSkillset } from "@skillset/core";
import { gitSafeEnv } from "@skillset/core/internal/git-env";
import { withLockProvenance } from "@skillset/core/internal/lock-provenance";

import { createTestFixtureRoot } from "../test-helpers/fixture-root";
import {
  initializeTestGitRepository,
  runTestGit,
} from "../test-helpers/git-remote";

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(
    roots.splice(0).map((root) => rm(root, { recursive: true, force: true }))
  );
});
const helperRoot = resolve(
  import.meta.dir,
  "../../.skillset/skills/skillset-adrs/scripts/lib"
);
const oldName = "20260101-example.md";
const newName = "0099-example.md";
async function fixture(native = false) {
  const disposableRoot = await createTestFixtureRoot(
    "adr-reference-ownership-"
  );
  roots.push(disposableRoot);
  const root = join(disposableRoot, "repo");
  await mkdir(root);
  for (const [path, content] of Object.entries({
    "skillset.yaml": `${native ? "workspace:\n  nativeAgents: true\n" : ""}compile:\n  targets: [claude, codex]\n`,
    [native ? "AGENTS.md" : ".skillset/RULES.md"]:
      `# Rules\n\nSee docs/adrs/drafts/${oldName}.\n`,
    ".skillset/skills/author/SKILL.md": `---\nname: author\ndescription: Authored references.\n---\n\nSee docs/adrs/drafts/${oldName}#decision.\n`,
    ".skillset/shared/unused.md": `Unreferenced shared docs/adrs/drafts/${oldName}.\n`,
    "docs/guide.md": `# Guide\n\nSee adrs/drafts/${oldName}.\n`,
    "docs/adrs/drafts/.gitkeep": "",
  }))
    await Bun.write(join(root, path), content);
  await buildSkillset(root);
  await initializeTestGitRepository(root, { disposableRoot });
  return root;
}
async function helper(root: string, action: "scan" | "rewrite") {
  const preflight = `import {referenceDocuments} from ${JSON.stringify(join(helperRoot, "reference-inventory.ts"))}; const documents = await referenceDocuments(process.cwd());`;
  const code =
    preflight +
    (action === "scan"
      ? `import {findInboundRefs} from ${JSON.stringify(join(helperRoot, "decision-map.ts"))}; console.log(JSON.stringify(findInboundRefs(${JSON.stringify(oldName)}, [], documents)));`
      : `import {rewriteDraftLinks} from ${JSON.stringify(join(helperRoot, "references.ts"))}; rewriteDraftLinks(${JSON.stringify(oldName)}, ${JSON.stringify(newName)}, documents);`);
  const child = Bun.spawn([process.execPath, "-e", code], {
    cwd: root,
    env: gitSafeEnv(),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  if (exitCode !== 0) throw new Error(stderr || stdout);
  return stdout;
}
test("inbound inventory reports canonical references without generated copies", async () => {
  const root = await fixture();
  const refs = JSON.parse(await helper(root, "scan")) as { fromPath: string }[];
  expect(refs.map((ref) => ref.fromPath)).toEqual([
    ".skillset/RULES.md",
    ".skillset/shared/unused.md",
    ".skillset/skills/author/SKILL.md",
    "docs/guide.md",
  ]);
});
test("draft link rewrite touches authored source and regenerates output only through build", async () => {
  const root = await fixture();
  const generatedPaths = [
    "AGENTS.md",
    ".claude/skills/author/SKILL.md",
    ".agents/skills/author/SKILL.md",
    "skillset.lock",
  ];
  const before = await Promise.all(
    generatedPaths.map((path) => readFile(join(root, path), "utf8"))
  );
  await helper(root, "rewrite");
  expect(
    await readFile(join(root, ".skillset/skills/author/SKILL.md"), "utf8")
  ).toContain(`${newName}#decision`);
  expect(await readFile(join(root, ".skillset/RULES.md"), "utf8")).toContain(
    newName
  );
  for (const [index, path] of generatedPaths.entries())
    expect(await readFile(join(root, path), "utf8")).toBe(before[index]!);
  await buildSkillset(root);
  expect(await readFile(join(root, "AGENTS.md"), "utf8")).toContain(newName);
  expect(
    await readFile(join(root, ".claude/skills/author/SKILL.md"), "utf8")
  ).toContain(newName);
});

test("mixed documents preserve generated blocks and rewrite authored examples with CRLF", async () => {
  const root = await fixture();
  const generated = `<!-- skillset:generated:start refs -->\r\nGenerated drafts/${oldName}\r\n<!-- skillset:generated:end refs -->`;
  const authored = `# Mixed\r\nAuthored drafts/${oldName}\r\n\r\n\`\`\`text\r\ndrafts/${oldName}\r\n\`\`\`\r\n`;
  const path = join(root, "docs/mixed.md");
  await Bun.write(path, authored + generated + "\r\n");
  const page = `---\ndescription: Generated page.\n---\n<!-- Generated by \`bun run docs:generate\`; do not edit directly. -->\n\n${oldName}\n`;
  await Bun.write(join(root, "docs/generated.md"), page);
  await helper(root, "rewrite");
  expect(await readFile(path, "utf8")).toBe(
    authored.replaceAll(`drafts/${oldName}`, newName) + generated + "\r\n"
  );
  expect(await readFile(join(root, "docs/generated.md"), "utf8")).toBe(page);
  const refs = JSON.parse(await helper(root, "scan")) as { fromPath: string }[];
  expect(
    refs.some(
      (ref) =>
        ref.fromPath === "docs/mixed.md" || ref.fromPath === "docs/generated.md"
    )
  ).toBe(false);
});

test("malformed generated boundaries fail before any reference rewrite", async () => {
  const root = await fixture();
  const path = join(root, ".skillset/skills/author/SKILL.md");
  const before = await readFile(path, "utf8");
  await Bun.write(
    join(root, "docs/broken.md"),
    `<!-- skillset:generated:start open -->\n${oldName}\n`
  );
  await expect(helper(root, "rewrite")).rejects.toThrow(
    "Invalid generated Markdown markers"
  );
  expect(await readFile(path, "utf8")).toBe(before);
});

test("native root guidance is authored while opaque, operational and symlink docs are excluded", async () => {
  const root = await fixture(true);
  const ignored = [
    ".skillset/cache/notes.md",
    ".skillset/snapshots/notes.md",
    ".skillset/releases/notes.md",
    ".skillset/_claude/notes.md",
  ];
  for (const path of ignored) await Bun.write(join(root, path), `${oldName}\n`);
  const outside = join(root, "../outside.md");
  await Bun.write(outside, `${oldName}\n`);
  await symlink(outside, join(root, "docs/linked.md"));
  const refs = JSON.parse(await helper(root, "scan")) as { fromPath: string }[];
  expect(refs.some((ref) => ref.fromPath === "AGENTS.md")).toBe(true);
  expect(
    refs.some(
      (ref) =>
        ignored.includes(ref.fromPath) || ref.fromPath === "docs/linked.md"
    )
  ).toBe(false);
  await helper(root, "rewrite");
  expect(await readFile(join(root, "AGENTS.md"), "utf8")).toContain(newName);
  for (const path of [...ignored, "../outside.md"])
    expect(await readFile(join(root, path), "utf8")).toBe(`${oldName}\n`);
});

test("untracked current locks still exclude generated source-adjacent Markdown", async () => {
  const root = await fixture();
  const path = ".skillset/shared/generated.md";
  await Bun.write(join(root, path), `${oldName}\n`);
  const lockPath = join(root, "skillset.lock");
  const lock = JSON.parse(await readFile(lockPath, "utf8"));
  lock.items[0].files.push(path);
  lock.items[0].fileModes[path] = "0644";
  await Bun.write(lockPath, JSON.stringify(withLockProvenance(lock)));
  await runTestGit(root, "rm", "--cached", "skillset.lock");
  const refs = JSON.parse(await helper(root, "scan")) as { fromPath: string }[];
  expect(refs.some((ref) => ref.fromPath === path)).toBe(false);
  await helper(root, "rewrite");
  expect(await readFile(join(root, path), "utf8")).toBe(`${oldName}\n`);
});

test("corrupt ownership locks stop before authored writes", async () => {
  const root = await fixture();
  const path = join(root, ".skillset/skills/author/SKILL.md");
  const before = await readFile(path, "utf8");
  await Bun.write(join(root, "skillset.lock"), "not JSON");
  await expect(helper(root, "rewrite")).rejects.toThrow("not valid JSON");
  expect(await readFile(path, "utf8")).toBe(before);
});

test("a partial workspace cannot fall back to documentation-only rewriting", async () => {
  const root = await fixture();
  const path = join(root, "docs/guide.md");
  const before = await readFile(path, "utf8");
  await rm(join(root, "skillset.yaml"));
  await expect(helper(root, "rewrite")).rejects.toThrow();
  expect(await readFile(path, "utf8")).toBe(before);
});

test("a symlinked docs root cannot authorize writes outside the repository", async () => {
  const root = await fixture();
  await rm(join(root, "docs"), { recursive: true });
  const outside = join(root, "../external-docs");
  await mkdir(outside);
  await Bun.write(join(outside, "guide.md"), `${oldName}\n`);
  await symlink(outside, join(root, "docs"));
  await expect(helper(root, "rewrite")).rejects.toThrow();
  expect(await readFile(join(outside, "guide.md"), "utf8")).toBe(
    `${oldName}\n`
  );
});
