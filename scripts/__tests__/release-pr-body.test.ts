import { describe, expect, test } from "bun:test";
import { readFile } from "node:fs/promises";

import { compactReleasePrBody } from "../release-pr-body";

interface WorkflowStep {
  env?: Record<string, string>;
  id?: string;
  if?: string;
  name?: string;
  run?: string;
}

const cliNotes =
  "## @skillset/cli@0.31.0\n\n### Minor Changes\n\n- abc123: Improve lock provenance.\n";
const alignedPackages = [
  "@skillset/native-darwin-arm64",
  "@skillset/native-darwin-x64",
  "@skillset/native-linux-arm64-glibc",
  "@skillset/native-linux-x64-glibc",
  "@skillset/native-win32-x64",
  "skillset",
];
const releaseBody = `Generated by Changesets.\n\n# Releases\n${cliNotes}${alignedPackages.map((name) => `## ${name}@0.31.0\n\n\n`).join("")}`;

describe("release PR body", () => {
  test("keeps notes and folds all empty package sections into one collapsed heading", () => {
    const result = compactReleasePrBody(releaseBody);
    expect(result).toStartWith(
      `Generated by Changesets.\n\n# Releases\n${cliNotes}`
    );
    expect(result.match(/<details>/gu)).toHaveLength(1);
    expect(result).toContain(
      "<summary><h2>Version-aligned packages</h2></summary>\n\nNo package-specific release notes."
    );
    expect(result).not.toContain("<details open");
    for (const name of alignedPackages) {
      expect(result).not.toContain(`## ${name}@0.31.0`);
      expect(result).toContain(`- \`${name}@0.31.0\``);
    }
    expect(result).not.toContain("- `@skillset/cli@0.31.0`");
  });

  test("is idempotent", () => {
    const result = compactReleasePrBody(releaseBody);
    expect(compactReleasePrBody(result)).toBe(result);
  });

  test("keeps package-specific notes for native and launcher packages", () => {
    const body =
      "# Releases\n## skillset@1.0.0\n\n### Patch Changes\n\n- Fix the launcher.\n## @skillset/native-darwin-arm64@1.0.0\n\n- Fix signing.\n";
    expect(compactReleasePrBody(body)).toBe(body);
  });

  test("preserves unknown headings and content outside Releases", () => {
    const prefix = "# Review notes\n## skillset@0.31.0\n\n# Releases\n";
    const suffix = "# Checklist\n\n- Review all packages.\n";
    const result = compactReleasePrBody(
      `${prefix}## skillset@0.31.0\n\n## unrelated@1.0.0\n\n${suffix}`
    );
    expect(result).toStartWith(prefix);
    expect(result).toContain("## unrelated@1.0.0");
    expect(result).toEndWith(suffix);
    expect(result.indexOf("</details>")).toBeLessThan(
      result.indexOf("# Checklist")
    );
  });

  test("does not mistake headings inside code fences for package sections", () => {
    const body =
      "# Releases\n## @skillset/cli@0.31.0\n\n```markdown\n## skillset@0.31.0\n```\n";
    expect(compactReleasePrBody(body)).toBe(body);
  });

  test.each([
    "The changelog information of each package has been omitted from this message, as the content exceeds the size limit.",
    "All release information have been omitted from this message, as the content exceeds the size limit.",
  ])("does not relabel truncated release notes as empty: %s", (warning) => {
    const body = `# Releases\n\n> ${warning}\n\n## skillset@0.31.0\n\n`;
    expect(compactReleasePrBody(body)).toBe(body);
  });

  test("keeps sections with comments or dependency-only notes", () => {
    const body =
      "# Releases\n## skillset@0.31.0\n\n<!-- Keep this note. -->\n## @skillset/cli@0.31.0\n\n- Updated dependencies.\n";
    expect(compactReleasePrBody(body)).toBe(body);
  });

  test("supports prerelease versions and CRLF", () => {
    const result = compactReleasePrBody(
      "# Releases\r\n## skillset@1.0.0-beta.1\r\n\r\n"
    );
    expect(result).toContain("- `skillset@1.0.0-beta.1`");
    expect(result.replaceAll("\r\n", "")).not.toContain("\n");
    expect(compactReleasePrBody(result)).toBe(result);
  });

  test.each([
    "",
    "# Releases\n",
    "## skillset@0.31.0\n",
    "# Releases\n## unrelated@1.0.0\n",
  ])("leaves bodies without empty release packages unchanged: %s", (body) => {
    expect(compactReleasePrBody(body)).toBe(body);
  });

  test("runs after Changesets and edits only its returned PR body", async () => {
    const workflow = Bun.YAML.parse(
      await readFile(
        new URL("../../.github/workflows/release.yml", import.meta.url),
        "utf-8"
      )
    ) as { jobs: { version: { steps: WorkflowStep[] } } };
    const { steps } = workflow.jobs.version;
    const changesetsIndex = steps.findIndex((step) => step.id === "changesets");
    const formatIndex = steps.findIndex(
      (step) => step.name === "Compact version PR release notes"
    );
    expect(formatIndex).toBeGreaterThan(changesetsIndex);
    const step = steps[formatIndex];
    if (!step) {
      throw new Error("Missing release notes formatter step");
    }
    expect(step.if).toBe("steps.changesets.outputs.pullRequestNumber != ''");
    expect(step.env).toEqual({
      GH_REPO: `\${{ github.repository }}`,
      GH_TOKEN: `\${{ github.token }}`,
      RELEASE_PR_NUMBER: `\${{ steps.changesets.outputs.pullRequestNumber }}`,
    });
    expect(step.run).toContain(
      'gh pr view "$RELEASE_PR_NUMBER" --json body --jq .body'
    );
    expect(step.run).toContain('bun scripts/release-pr-body.ts "$body_file"');
    expect(step.run).toContain(
      'gh pr edit "$RELEASE_PR_NUMBER" --body-file "$formatted_file"'
    );
  });
});
