import { readFileSync } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import { basename, join, relative } from "node:path";

import {
  MISSING_PATH_ENOENT,
  pathExists,
} from "@skillset/core/internal/fs-existence";
import {
  REPO_OPERATIONAL_CACHE_ROOT,
  resolveRepoOperationalCachePath,
} from "@skillset/core/internal/operational-cache";
import { OUTPUT_BACKUP_ROOT } from "@skillset/core/internal/output-safety";
import {
  assertRealPathInside,
  isPathInside,
} from "@skillset/core/internal/path";
import { renderBuildGraph } from "@skillset/core/internal/render";
import { loadBuildGraph } from "@skillset/core/internal/resolver";
import { sourceMarkdownDocuments } from "@skillset/core/internal/source-rename-paths";

import { hasGeneratedOwnership } from "../../../../../scripts/docs-reference.ts";
import { maskGeneratedMarkdown } from "../../../../../scripts/docs/markdown.ts";
import {
  isLockPath,
  readGeneratedPaths,
} from "../../../../../scripts/generated-merge-policy-guard.ts";

export interface ReferenceDocument {
  readonly path: string;
  readonly filename: string;
}

/** Repo-local contributor inventory: canonical source and authored non-ADR docs. */
export async function referenceDocuments(
  root: string
): Promise<readonly ReferenceDocument[]> {
  // The ADR helper also supports documentation-only repositories. A partial
  // Skillset workspace must still validate; only true absence uses docs alone.
  const hasWorkspace =
    (await pathExists(join(root, "skillset.yaml"), {
      missing: MISSING_PATH_ENOENT,
      probe: "lstat",
    })) ||
    (await pathExists(join(root, ".skillset"), {
      missing: MISSING_PATH_ENOENT,
      probe: "lstat",
    }));
  const graph = hasWorkspace ? await loadBuildGraph(root) : undefined;
  // Current render ownership covers fresh outputs; committed locks also protect
  // prior generated paths that the current configuration no longer emits.
  const rendered = graph === undefined ? [] : await renderBuildGraph(graph);
  const generated = new Set([
    ...(await readGeneratedPaths(
      root,
      rendered.map((file) => file.path).filter(isLockPath)
    )),
    ...rendered.map((file) => file.path),
  ]);
  const ignored = [
    join(root, REPO_OPERATIONAL_CACHE_ROOT),
    resolveRepoOperationalCachePath(root),
    join(root, OUTPUT_BACKUP_ROOT),
  ];
  const paths = new Set(
    graph === undefined ? [] : await sourceMarkdownDocuments(graph)
  );
  if (graph?.nativeRootRuleSource !== undefined)
    paths.add(join(root, "AGENTS.md"));
  await visitDocs(join(root, "docs"), join(root, "docs/adrs"), paths);
  const documents: ReferenceDocument[] = [];
  for (const path of [...paths].sort()) {
    if (
      ignored.some((directory) =>
        isPathInside(directory, path, { allowEqual: true })
      )
    )
      continue;
    const logical = relative(root, path).replaceAll("\\", "/");
    if (generated.has(logical)) continue;
    await assertRealPathInside(root, path);
    const content = await readFile(path, "utf8");
    if (hasGeneratedOwnership(content)) continue;
    maskGeneratedMarkdown(content); // Validate every candidate before a command writes.
    documents.push({ filename: basename(path), path });
  }
  return documents;
}

async function visitDocs(
  directory: string,
  adrDirectory: string,
  paths: Set<string>
): Promise<void> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return;
    throw error;
  }
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (path === adrDirectory) continue;
    if (entry.isDirectory()) await visitDocs(path, adrDirectory, paths);
    else if (entry.isFile() && entry.name.endsWith(".md")) paths.add(path);
  }
}

export function referenceText(path: string): string {
  return maskGeneratedMarkdown(readFileSync(path, "utf8"));
}

/** Apply only matches visible in the ownership mask, keeping generated bytes intact. */
export function rewriteReferenceText(
  content: string,
  pattern: RegExp,
  replacement: string
): string {
  const visible = maskGeneratedMarkdown(content);
  const matches = [...visible.matchAll(pattern)];
  for (const match of matches.reverse()) {
    const start = match.index!;
    content =
      content.slice(0, start) +
      replacement +
      content.slice(start + match[0].length);
  }
  return content;
}
