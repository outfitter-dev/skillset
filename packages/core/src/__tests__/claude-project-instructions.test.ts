import { describe, expect, it } from "bun:test";
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { createTestFixtureRoot } from "../../../../scripts/test-helpers/fixture-root";

import { buildSkillset, buildSkillsetResult } from "@skillset/core";

const DIALECT_RULES = `---
dialect: claude
---

# Authoring model

Keep CLAUDE.md current.
`;

async function authoringFixture(
  overrides: Record<string, string | null> = {}
): Promise<string> {
  const root = await createTestFixtureRoot("skillset-claude-instructions-");
  await cp(join(process.cwd(), "fixtures/authoring-model"), root, {
    recursive: true,
  });
  for (const [path, content] of Object.entries(overrides)) {
    const destination = join(root, path);
    if (content === null) {
      await rm(destination, { force: true });
      continue;
    }
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
  return root;
}

async function withFrontPage(root: string, placement: string): Promise<void> {
  const configPath = join(root, "skillset.yaml");
  const config = await readFile(configPath, "utf8");
  await writeFile(
    configPath,
    config.replace("compile:\n", `compile:\n  instruction_front_page: ${placement}\n`)
  );
}

const exists = (path: string): Promise<boolean> => Bun.file(path).exists();

async function workspaceLockItems(
  root: string
): Promise<readonly Record<string, unknown>[]> {
  const lock = JSON.parse(await readFile(join(root, "skillset.lock"), "utf8")) as {
    readonly items: readonly Record<string, unknown>[];
  };
  return lock.items;
}

async function filesBelow(root: string): Promise<readonly string[]> {
  const paths: string[] = [];
  async function visit(path: string): Promise<void> {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const child = join(path, entry.name);
      if (entry.isDirectory()) await visit(child);
      else paths.push(relative(root, child).replaceAll("\\", "/"));
    }
  }
  await visit(root);
  return paths.sort();
}

describe("SET-580 Claude project instructions", () => {
  it("renders RULES.md to .claude/CLAUDE.md with provenance and a lock entry", async () => {
    const root = await authoringFixture();

    await buildSkillset(root);

    expect(await readFile(join(root, ".claude/CLAUDE.md"), "utf8")).toBe(
      [
        "<!-- Generated by skillset@0.1.0 from .skillset/RULES.md. Do not edit directly. -->",
        "",
        "# Authoring model",
        "",
        "Keep source ownership explicit.",
        "",
      ].join("\n")
    );
    expect(await exists(join(root, "CLAUDE.md"))).toBe(false);
    expect(await workspaceLockItems(root)).toContainEqual(
      expect.objectContaining({
        consumers: [{ phase: "delta", target: "claude" }],
        files: [".claude/CLAUDE.md"],
        kind: "rule",
        name: "RULES",
        outputPath: ".claude/CLAUDE.md",
        owner: { target: "claude" },
        sourcePath: ".skillset/RULES.md",
      })
    );
    // Only the front page feeds CLAUDE.md; rules keep their own projection.
    expect(await exists(join(root, ".claude/rules/RULES.md"))).toBe(false);
    expect(await exists(join(root, ".claude/rules/testing.md"))).toBe(true);
  });

  it("renders nothing without a RULES.md front page", async () => {
    const root = await authoringFixture({ ".skillset/RULES.md": null });

    await buildSkillset(root);

    expect(await exists(join(root, ".claude/CLAUDE.md"))).toBe(false);
    expect(await exists(join(root, "CLAUDE.md"))).toBe(false);
    const outputs = (await workspaceLockItems(root)).map((item) => item.outputPath);
    expect(outputs).not.toContain(".claude/CLAUDE.md");
    expect(outputs).not.toContain("CLAUDE.md");
  });

  it("keeps Claude dialect verbatim in CLAUDE.md and translates it for AGENTS.md", async () => {
    const root = await authoringFixture({ ".skillset/RULES.md": DIALECT_RULES });

    await buildSkillset(root);

    const claude = await readFile(join(root, ".claude/CLAUDE.md"), "utf8");
    const agents = await readFile(join(root, "AGENTS.md"), "utf8");
    expect(claude).toContain("Keep CLAUDE.md current.");
    expect(agents).toContain("Keep AGENTS.md current.");
    expect(agents).not.toContain("Keep CLAUDE.md current.");
  });

  it("renders the RULES.md front page first in root AGENTS.md [SET-742]", async () => {
    const root = await authoringFixture({
      ".skillset/RULES.md": "# Front page\n",
      ".skillset/rules/01-basics.md": "# Basics\n",
    });

    await buildSkillset(root);

    const agents = await readFile(join(root, "AGENTS.md"), "utf8");
    expect(agents.startsWith("# Front page\n")).toBe(true);
    expect(agents.indexOf("# Front page")).toBeLessThan(agents.indexOf("# Basics"));
  });

  it("renders root CLAUDE.md instead when instruction_front_page is repo-root", async () => {
    const root = await authoringFixture();
    await withFrontPage(root, "repo-root");

    await buildSkillset(root);

    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toContain(
      "Do not edit directly. -->\n\n# Authoring model"
    );
    expect(await exists(join(root, ".claude/CLAUDE.md"))).toBe(false);
  });

  it("rejects an instruction_front_page value outside the two placements", async () => {
    const root = await authoringFixture();
    await withFrontPage(root, "elsewhere");

    await expect(buildSkillset(root)).rejects.toThrow(
      "compile.instruction_front_page must be one of claude-dir, repo-root"
    );
  });

  it("removes the old placement when the configured placement changes", async () => {
    const root = await authoringFixture();
    await buildSkillset(root);
    await withFrontPage(root, "repo-root");

    const result = await buildSkillsetResult(root);

    expect(await exists(join(root, "CLAUDE.md"))).toBe(true);
    expect(await exists(join(root, ".claude/CLAUDE.md"))).toBe(false);
    expect(result.diagnostics.map((diagnostic) => diagnostic.code)).not.toContain(
      "claude-instructions-duplicate-root"
    );
  });

  it("warns about an unmanaged CLAUDE.md beside the generated one and leaves it untouched", async () => {
    const handWritten = "# Hand written\n\nLocal notes.\n";
    const root = await authoringFixture({ "CLAUDE.md": handWritten });

    const result = await buildSkillsetResult(root);

    expect(result.ok).toBe(true);
    expect(result.diagnostics).toContainEqual(
      expect.objectContaining({
        code: "claude-instructions-duplicate-root",
        outputPath: "CLAUDE.md",
        severity: "warning",
        target: "claude",
      })
    );
    const warning = result.diagnostics.find(
      (diagnostic) => diagnostic.code === "claude-instructions-duplicate-root"
    );
    expect(warning?.message).toContain("CLAUDE.md");
    expect(warning?.message).toContain(".claude/CLAUDE.md");
    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toBe(handWritten);
    expect(await exists(join(root, ".claude/CLAUDE.md"))).toBe(true);
  });

  it("does not warn when Skillset renders no Claude project instructions", async () => {
    const root = await authoringFixture({
      ".skillset/RULES.md": null,
      "CLAUDE.md": "# Hand written\n",
    });

    const result = await buildSkillsetResult(root);

    expect(result.diagnostics.map((diagnostic) => diagnostic.code)).not.toContain(
      "claude-instructions-duplicate-root"
    );
  });

  it("rebases RULES.md and scoped-rule links for each destination's depth [SET-755]", async () => {
    const root = await authoringFixture({
      ".skillset/RULES.md": "# Guide\n\nRead [tenets](docs/tenets.md#why) and [site](https://example.com).\n",
      ".skillset/rules/services/linking.md": "See [the service readme](README.md).\n\n{{> service-links}}\n",
      ".skillset/shared/partials/service-links.md": "Also read [the runbook](RUNBOOK.md).\n",
    });

    await buildSkillset(root);

    expect(await readFile(join(root, "AGENTS.md"), "utf8")).toContain(
      "[tenets](docs/tenets.md#why) and [site](https://example.com)"
    );
    expect(await readFile(join(root, ".claude/CLAUDE.md"), "utf8")).toContain(
      "[tenets](../docs/tenets.md#why) and [site](https://example.com)"
    );
    expect(await readFile(join(root, "services/AGENTS.md"), "utf8")).toContain(
      "[the service readme](README.md)"
    );
    expect(await readFile(join(root, ".claude/rules/services/linking.md"), "utf8")).toContain(
      "[the service readme](../../../services/README.md)"
    );
    expect(await readFile(join(root, ".cursor/rules/services/linking.mdc"), "utf8")).toContain(
      "[the service readme](../../../services/README.md)"
    );
    expect(await readFile(join(root, "services/AGENTS.md"), "utf8")).toContain(
      "[the runbook](RUNBOOK.md)"
    );
    expect(await readFile(join(root, ".claude/rules/services/linking.md"), "utf8")).toContain(
      "[the runbook](../../../services/RUNBOOK.md)"
    );
  });

  it("never writes CLAUDE.md into a plugin package", async () => {
    const root = await authoringFixture();

    await buildSkillset(root);

    const packaged = (await filesBelow(join(root, "plugins"))).filter((path) =>
      path.endsWith("CLAUDE.md")
    );
    expect(packaged).toEqual([]);
  });
});
