const CLAUDE_RULES_OUTPUT_ROOT = ".claude/rules";

/**
 * Claude reads project instructions from either placement and concatenates
 * both into context, so Skillset renders exactly one of them.
 */
export const CLAUDE_PROJECT_INSTRUCTION_PATHS: Readonly<
  Record<InstructionFrontPageDestination, string>
> = {
  "claude-dir": ".claude/CLAUDE.md",
  "repo-root": "CLAUDE.md",
};

export async function renderRules(
  graph: BuildGraph,
  lockRoots: Map<string, LockRoot>
): Promise<readonly RenderedFile[]> {
  const rendered: RenderedFile[] = [];
  rendered.push(...(await renderClaudeRules(graph, lockRoots)));
  rendered.push(...(await renderClaudeProjectInstructions(graph, lockRoots)));
  rendered.push(...(await renderAgentInstructionFiles(graph, lockRoots)));
  rendered.push(...(await renderCursorRules(graph, lockRoots)));
  return rendered;
}

async function renderClaudeRules(
  graph: BuildGraph,
  lockRoots: Map<string, LockRoot>
): Promise<readonly RenderedFile[]> {
  const rendered: RenderedFile[] = [];

  for (const rule of graph.rules.filter(
    (sourceRule) =>
      sourceRule.targets.claude.enabled &&
      !sourceRule.rootFrontPage &&
      !hasWildcardScope(sourceRule)
  )) {
    const targetFile = join(CLAUDE_RULES_OUTPUT_ROOT, rule.relativePath);
    const markdown = await renderClaudeRuleMarkdown(graph, rule, targetFile);
    const file = textFile(
      targetFile,
      markdown.content,
      relative(graph.rootPath, rule.sourcePath)
    );
    rendered.push(file);
    lockRootsFor(lockRoots, CLAUDE_RULES_OUTPUT_ROOT, "claude").items.push(
      lockItemForRule({
        files: [file],
        graph,
        name: rule.id,
        outputRoot: CLAUDE_RULES_OUTPUT_ROOT,
        outputPath: targetFile,
        preprocessDependencies: markdown.preprocessDependencies,
        sourceHash: hashTextRule(
          rule,
          markdown.preprocessDependencies,
          graph.rootPath
        ),
        ...(rule.sourceOrigin === undefined
          ? {}
          : { sourceOrigin: rule.sourceOrigin }),
        sourcePath: relative(graph.rootPath, rule.sourcePath),
      })
    );
  }

  return rendered;
}

/**
 * Render the `RULES.md` front page to the Claude project instruction file
 * that `compile.instruction_front_page` names. Only the front page feeds it:
 * unscoped rules already reach Claude's launch context through
 * `.claude/rules/`. The body stays in its authored dialect, unlike the Codex
 * `AGENTS.md` projection of the same source.
 */
async function renderClaudeProjectInstructions(
  graph: BuildGraph,
  lockRoots: Map<string, LockRoot>
): Promise<readonly RenderedFile[]> {
  const rule = graph.rules.find(
    (sourceRule) => sourceRule.rootFrontPage && sourceRule.targets.claude.enabled
  );
  if (rule === undefined) return [];

  const targetFile =
    CLAUDE_PROJECT_INSTRUCTION_PATHS[graph.root.compile.instructionFrontPage];
  const sourcePath = relative(graph.rootPath, rule.sourcePath);
  const preprocessDependencies = new Set<string>();
  const body = normalizeRuleBody(
    await renderRuleBody(graph, rule, targetFile, preprocessDependencies)
  );
  const content = [
    `<!-- Generated by ${GENERATED_BY} from ${normalizeWorkspacePath(sourcePath)}. Do not edit directly. -->`,
    "",
    ...(body.length === 0 ? [] : [body]),
    "",
  ].join("\n");
  const file = textFile(targetFile, content, sourcePath);
  const dependencies = formattedPreprocessDependencies(
    graph,
    preprocessDependencies
  );
  lockRootsFor(lockRoots, WORKSPACE_LOCK_ROOT, "workspace").items.push(
    lockItemForRule({
      consumers: [{ phase: "delta", target: "claude" }],
      files: [file],
      graph,
      name: rule.id,
      owner: { target: "claude" },
      outputRoot: WORKSPACE_LOCK_ROOT,
      outputPath: targetFile,
      preprocessDependencies: dependencies,
      sourceHash: hashTextRule(rule, dependencies, graph.rootPath),
      ...(rule.sourceOrigin === undefined
        ? {}
        : { sourceOrigin: rule.sourceOrigin }),
      sourcePath,
    })
  );
  return [file];
}

async function renderAgentInstructionFiles(
  graph: BuildGraph,
  lockRoots: Map<string, LockRoot>
): Promise<readonly RenderedFile[]> {
  const projections = await planAgentInstructionProjections(
    graph,
    codexRuleDestinations
  );
  const rendered: LogicalRenderedFile[] = [];
  const lockItems = new Map<
    string,
    {
      readonly consumers: OutputConsumer[];
      readonly file: LogicalRenderedFile;
      readonly markdown: RenderedRuleMarkdown;
      readonly owner: OutputOwner;
      readonly rules: readonly SourceRule[];
    }
  >();

  for (const projection of projections) {
    const { destination, outputProjection, rules } = projection;
    const markdown = await renderCodexAgentsMarkdown(graph, rules, destination);
    const rootFrontPage = rules.find((rule) => rule.rootFrontPage);
    const sourcePath =
      rootFrontPage === undefined
        ? workspaceRelativeSourcePath(graph, graph.rulesDir)
        : relative(graph.rootPath, rootFrontPage.sourcePath);
    const file = {
      ...textFile(destination, markdown.content, sourcePath),
      outputProjection,
    };
    rendered.push(file);
    const existing = lockItems.get(destination);
    const owner: OutputOwner =
      outputProjection.consumer.phase === "baseline"
        ? { standardProfile: outputProjection.consumer.standardProfile }
        : { target: outputProjection.consumer.target };
    lockItems.set(destination, {
      consumers: [
        ...(existing?.consumers ?? []),
        outputProjection.consumer,
      ],
      file: existing?.file ?? file,
      markdown: existing?.markdown ?? markdown,
      owner:
        outputProjection.consumer.phase === "baseline"
          ? owner
          : (existing?.owner ?? owner),
      rules: existing?.rules ?? rules,
    });
  }

  for (const [destination, item] of lockItems) {
    const rootFrontPage = item.rules.find((rule) => rule.rootFrontPage);
    const sourcePath =
      rootFrontPage === undefined
        ? workspaceRelativeSourcePath(graph, graph.rulesDir)
        : relative(graph.rootPath, rootFrontPage.sourcePath);
    lockRootsFor(lockRoots, WORKSPACE_LOCK_ROOT, "workspace").items.push(
      lockItemForRule({
        consumers: item.consumers,
        files: [item.file],
        graph,
        name: destination,
        owner: item.owner,
        outputRoot: WORKSPACE_LOCK_ROOT,
        outputPath: destination,
        preprocessDependencies: item.markdown.preprocessDependencies,
        sourceHash: hashRules(
          item.rules,
          item.markdown.preprocessDependencies,
          graph.rootPath
        ),
        sourcePath,
        ...(item.markdown.transforms === undefined
          ? {}
          : { transforms: item.markdown.transforms }),
      })
    );
  }

  return rendered;
}

