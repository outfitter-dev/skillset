function cursorRuleRelativePath(path: string): string {
  return path.replace(/\.md$/u, ".mdc");
}

async function renderClaudeRuleMarkdown(
  graph: BuildGraph,
  rule: SourceRule,
  outputPath: string
): Promise<RenderedRuleMarkdown> {
  const paths = deriveRuleGlobs(rule, escapeClaudeGlobLiteral);
  const frontmatter: JsonRecord =
    paths.length === 0 ? {} : { paths: [...paths] };
  const preprocessDependencies = new Set<string>();
  const body = await renderRuleBody(
    graph,
    rule,
    outputPath,
    preprocessDependencies
  );
  return {
    content: stringifyOptionalMarkdown(frontmatter, body),
    preprocessDependencies: formattedPreprocessDependencies(
      graph,
      preprocessDependencies
    ),
  };
}

async function renderCursorRuleMarkdown(
  graph: BuildGraph,
  rule: SourceRule,
  outputPath: string
): Promise<RenderedRuleMarkdown> {
  const paths = deriveRuleGlobs(rule);
  const description =
    readString(rule.frontmatter, "description") ??
    readString(rule.frontmatter, "summary") ??
    readString(rule.frontmatter, "title") ??
    rule.id;
  const frontmatter: JsonRecord = {
    description,
    alwaysApply: paths.length === 0,
    ...(paths.length === 0 ? {} : { globs: [...paths] }),
  };
  const preprocessDependencies = new Set<string>();
  const body = await renderRuleBody(
    graph,
    rule,
    outputPath,
    preprocessDependencies
  );
  return {
    content: renderValidatedMarkdown(
      frontmatter,
      normalizeRuleBody(body),
      `${relative(graph.rootPath, rule.sourcePath)} -> ${outputPath}`
    ),
    preprocessDependencies: formattedPreprocessDependencies(
      graph,
      preprocessDependencies
    ),
  };
}

async function renderCodexAgentsMarkdown(
  graph: BuildGraph,
  rules: readonly SourceRule[],
  outputPath: string
): Promise<RenderedRuleMarkdown> {
  // A file that combines contributions, or whose one contribution narrows with
  // `paths:`, wraps each rule in an XML section carrying its source path and
  // derived scope; XML survives every provider's processing where comments do
  // not. A lone rule without `paths:` and the RULES.md front page stay bare.
  // Ordering follows the already-sorted rule list, except that the front page
  // always leads. Claude-dialect sources lower through the transform engine
  // for this codex projection; the .claude/rules projection stays untouched.
  const counts = new Map<string, number>();
  const preprocessDependencies = new Set<string>();
  const ordered = [
    ...rules.filter((rule) => rule.rootFrontPage),
    ...rules.filter((rule) => !rule.rootFrontPage),
  ];
  const sections = ordered.map(async (rule) => {
    const body = await renderRuleBody(
      graph,
      rule,
      outputPath,
      preprocessDependencies
    );
    if (rule.dialect !== "claude") return { rule, body };
    const translated = translateClaudeDialect(body);
    for (const transform of translated.transforms) {
      counts.set(
        transform.intent,
        (counts.get(transform.intent) ?? 0) + transform.count
      );
    }
    return { rule, body: translated.text };
  });
  const resolvedSections = (await Promise.all(sections)).filter(
    (section) => section.body.length > 0
  );
  const wrap =
    resolvedSections.length > 1 ||
    resolvedSections.some(
      (section) => !section.rule.rootFrontPage && readRulePaths(section.rule).length > 0
    );
  const renderedSections = resolvedSections.map((section) =>
    section.rule.rootFrontPage || !wrap
      ? section.body
      : renderRuleSection(graph, section.rule, section.body)
  );
  const hasRootFrontPage = resolvedSections.some(
    (section) => section.rule.rootFrontPage && section.body.length > 0
  );
  const content = [
    ...(hasRootFrontPage
      ? []
      : [
          `<!-- Generated by ${GENERATED_BY} from ${workspaceRelativeSourcePath(graph, graph.rulesDir)}. Do not edit directly. -->`,
          "",
        ]),
    renderedSections.join("\n\n"),
    "",
  ].join("\n");
  const transforms = [...counts.entries()]
    .sort(([left], [right]) => compareStrings(left, right))
    .map(([intent, count]) => ({ count, intent }));
  return {
    content,
    preprocessDependencies: formattedPreprocessDependencies(
      graph,
      preprocessDependencies
    ),
    transforms,
  };
}

// Scope alone decides a rule's AGENTS.md, so no destination depends on which
// files exist in the working tree. A wildcard scope has no destination until
// SET-574 expands it against the tree.
async function codexRuleDestinations(
  _graph: BuildGraph,
  rule: SourceRule
): Promise<readonly string[]> {
  if (hasWildcardScope(rule)) return [];
  return [codexRuleDestination(rule)];
}

/**
 * The canonical XML section for one rule in a generated `AGENTS.md`: the tag
 * names the rule, `source` is the reverse-incorporation anchor, and
 * `applies_to` is a scope signal to the reading agent, not enforcement.
 */
function renderRuleSection(graph: BuildGraph, rule: SourceRule, body: string): string {
  const tag = ruleSectionTagName(rule);
  const source = normalizeWorkspacePath(relative(graph.rootPath, rule.sourcePath));
  const appliesTo = ruleAppliesTo(rule);
  if (body.split("\n").some((line) => line.trim() === `</${tag}>`)) {
    throw new Error(
      `skillset: ${source} contains its own closing section tag </${tag}>, which would end its generated AGENTS.md section early; set a different frontmatter name or change that line`
    );
  }
  if (source.includes("`") || appliesTo.includes("`")) {
    throw new Error(`skillset: ${source} cannot carry a backtick into a generated AGENTS.md section attribute; rename the rule or its directory`);
  }
  return [
    `<${tag}`,
    `  source="${escapeXmlAttribute(source)}"`,
    `  applies_to="${escapeXmlAttribute(appliesTo)}" >`,
    "",
    body,
    "",
    `</${tag}>`,
  ].join("\n");
}

/**
 * Frontmatter `name`, else the filename stem, lowercased, with each run of
 * characters outside `[a-z0-9]` collapsed to `_`, trimmed of `_`, prefixed
 * with `_` when it starts with a digit, and `rule` when nothing is left.
 */
export function ruleSectionTagName(rule: SourceRule): string {
  const stem = rule.relativePath.split("/").at(-1)?.replace(/\.md$/u, "") ?? "";
  const name = readString(rule.frontmatter, "name") ?? stem;
  const sanitized = name
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/gu, "_")
    .replaceAll(/^_+|_+$/gu, "");
  if (sanitized.length === 0) return "rule";
  return /^[0-9]/u.test(sanitized) ? `_${sanitized}` : sanitized;
}

/**
 * Repository-relative scope the rule applies to: `<dir>/**` for a scoped rule,
 * `**` when unscoped, or each `paths:` entry joined onto the scope, sorted and
 * comma-separated. Literal brackets stay unescaped because this describes where
 * the file sits rather than being an evaluated glob.
 */
export function ruleAppliesTo(rule: SourceRule): string {
  if (hasWildcardScope(rule)) {
    throw new Error(
      `skillset: ${rule.relativePath} has an unexpanded wildcard scope; applies_to needs the concrete directory (SET-574)`
    );
  }
  const globs = deriveRuleGlobs(rule);
  return globs.length === 0 ? "**" : globs.join(", ");
}

/** Keep a path that contains `&`, `<`, `>` or `"` a valid attribute value. */
function escapeXmlAttribute(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function codexRuleDestination(rule: SourceRule): string {
  return rule.scopeDir === "" ? "AGENTS.md" : `${rule.scopeDir}/AGENTS.md`;
}

function hasWildcardScope(rule: SourceRule): boolean {
  return (rule.segments ?? []).some(
    (segment) => segment.classification !== "literal"
  );
}

/**
 * Globs for providers that enforce rule scope natively. `paths:` is relative
 * to the rule's scope directory; a scoped rule without `paths:` covers its
 * whole scope, and an unscoped rule without `paths:` has no globs.
 * `escapeScope` transforms only the literal scope directory, never an
 * authored pattern, so bracket expressions in `paths:` keep their meaning.
 */
function deriveRuleGlobs(
  rule: SourceRule,
  escapeScope: (scope: string) => string = (scope) => scope
): readonly string[] {
  const paths = readRulePaths(rule);
  if (rule.scopeDir === "") return [...paths].sort(compareStrings);
  const scope = escapeScope(rule.scopeDir);
  if (paths.length === 0) return [`${scope}/**`];
  return paths
    .map((path) => `${scope}/${path.replace(/^\.\//u, "")}`)
    .sort(compareStrings);
}

/**
 * Escape glob metacharacters in a literal scope directory so the derived Claude
 * glob matches only that directory. Claude documents that an unescaped `[`
 * outside a valid bracket expression matches nothing.
 */
function escapeClaudeGlobLiteral(value: string): string {
  return value.replaceAll(/[[\]*?{}]/gu, (character) => `\\${character}`);
}

/**
 * Render results for rule scope that the rendered files cannot show: a
 * wildcard scope that writes nothing, `paths:` narrowing Codex cannot
 * enforce, and Cursor globs whose literal punctuation has no verified escape.
 */
export function ruleScopeRenderResults(
  graph: BuildGraph,
  mapOutputPath: (path: string) => string = (path) => path
): readonly SkillsetRenderResult[] {
  const outcomes: SkillsetRenderResult[] = [];
  const cursorRoot = posix.join(normalizeWorkspacePath(targetProjectRoot(graph, "cursor")), "rules");
  // The Agent Instructions baseline renders every applicable rule regardless of
  // provider toggles, so its losses are recorded against the standard too.
  const baselineActive = graph.standardProjections.adopted.includes("agent-instructions");
  const consumers = (rule: SourceRule) => [
    ...(baselineActive ? [{ standardProfile: "agent-instructions" as const }] : []),
    ...(rule.targets.codex.enabled ? [{ target: "codex" as const }] : []),
  ];
  for (const rule of graph.rules) {
    if (rule.rootFrontPage) continue;
    const sourcePath = normalizeWorkspacePath(relative(graph.rootPath, rule.sourcePath));
    const sourceUnit = selectorForRule(rule.id);
    if (hasWildcardScope(rule)) {
      const reason = `wildcard rule scope ${rule.scopeDir} renders nothing until SET-574 expands [.] and [...] against the repository tree`;
      if (baselineActive) {
        outcomes.push(defineRenderResult({
          destination: "AGENTS.md",
          featureId: "rule-wildcard-scope-pending",
          policy: "unsupported:error",
          reason,
          sourcePath,
          sourceUnit,
          standardProfile: "agent-instructions",
          status: "unsupported",
        }));
      }
      for (const target of targetNames()) {
        if (!rule.targets[target].enabled) continue;
        outcomes.push(defineRenderResult({
          destination: "rule",
          featureId: "rule-wildcard-scope-pending",
          policy: "unsupported:error",
          reason,
          sourcePath,
          sourceUnit,
          status: "unsupported",
          target,
        }));
      }
      continue;
    }
    const paths = readRulePaths(rule);
    if (paths.length > 0) {
      const destination = codexRuleDestination(rule);
      for (const consumer of consumers(rule)) {
        outcomes.push(defineRenderResult({
          destination: "AGENTS.md",
          featureId: "codex-rule-paths-not-enforceable",
          outputs: [{ path: mapOutputPath(destination) }],
          reason: `${destination} applies to its whole directory, so paths: ${paths.join(", ")} cannot narrow it; the rule applies to all of ${rule.scopeDir === "" ? "the repository" : `${rule.scopeDir}/`}`,
          sourcePath,
          sourceUnit,
          status: "degraded",
          ...consumer,
        }));
      }
    }
    if (
      rule.targets.cursor.enabled &&
      /[[\]()*?{}]/u.test(rule.scopeDir)
    ) {
      outcomes.push(defineRenderResult({
        destination: "rule",
        featureId: "cursor-rule-glob-escaping-unverified",
        outputs: [{ path: mapOutputPath(posix.join(cursorRoot, cursorRuleRelativePath(rule.relativePath))) }],
        reason: "Cursor documents no escape for glob characters in rule globs, so a scope directory containing [, ], (, ), *, ?, { or } ships unescaped and may not match only that directory",
        sourcePath,
        sourceUnit,
        status: "degraded",
        target: "cursor",
      }));
    }
  }
  return outcomes;
}

function workspaceRelativeSourcePath(
  graph: BuildGraph,
  sourcePath: string
): string {
  return graph.sourceDir === "."
    ? sourcePath
    : join(graph.sourceDir, sourcePath);
}

export function readRulePaths(rule: SourceRule): readonly string[] {
  const value = rule.frontmatter.paths;
  if (value === undefined) return [];
  if (typeof value === "string")
    return [readNonEmptyRuleString(value, `${rule.sourcePath}.paths`)];
  if (Array.isArray(value) && value.every((item) => typeof item === "string")) {
    return value.map((item) =>
      readNonEmptyRuleString(item, `${rule.sourcePath}.paths`)
    );
  }
  throw new Error(
    `skillset: expected ${rule.sourcePath}.paths to be a string or string array`
  );
}

function readNonEmptyRuleString(value: string, label: string): string {
  const trimmed = value.trim();
  if (trimmed.length === 0) {
    throw new Error(
      `skillset: expected ${label} entries to be non-empty strings`
    );
  }
  // paths: only narrows within the rule's scope directory.
  if (
    trimmed.startsWith("/") ||
    /^[A-Za-z]:/u.test(trimmed) ||
    trimmed.split(/[\\/]/u).includes("..")
  ) {
    throw new Error(
      `skillset: ${label} entry ${trimmed} leaves the rule's scope; paths: is relative to the rule's directory and cannot be absolute or use ..`
    );
  }
  return trimmed;
}

function stringifyOptionalMarkdown(
  frontmatter: JsonRecord,
  body: string
): string {
  const normalizedBody = normalizeRuleBody(body);
  if (Object.keys(frontmatter).length === 0) return `${normalizedBody}\n`;
  return renderValidatedMarkdown(
    frontmatter,
    normalizedBody,
    "generated instruction markdown"
  );
}

async function renderRuleBody(
  graph: BuildGraph,
  rule: SourceRule,
  outputPath: string,
  preprocessDependencies: Set<string>
): Promise<string> {
  return preprocessText(normalizeRuleBody(rule.body), {
    frontmatter: rule.frontmatter,
    preprocessDependencies,
    rootPath: graph.rootPath,
    sourcePath: rule.sourcePath,
    sourceRoot: graph.sourceRoot,
    renderPathReference: (reference) =>
      normalizeWorkspacePath(
        relative(
          dirname(resolve(graph.rootPath, outputPath)),
          reference.resolvedPath
        )
      ),
    variables: ruleVariables(graph, rule, outputPath),
  });
}

function ruleVariables(
  graph: BuildGraph,
  rule: SourceRule,
  outputPath: string
): Readonly<Record<string, string>> {
  const outputDir = outputDirectory(outputPath);
  const sourceRule = relative(graph.rootPath, rule.sourcePath).replaceAll(
    "\\",
    "/"
  );
  return {
    "skillset.output_dir": outputDir,
    "skillset.repo_root": relativeOutputPath(outputDir, ""),
    "skillset.source_rule": sourceRule,
  };
}

function normalizeRuleBody(body: string): string {
  return body.replaceAll(/\r\n?/g, "\n").replace(/^\n+/, "").trimEnd();
}

function outputDirectory(outputPath: string): string {
  const directory = normalizeWorkspacePath(dirname(outputPath));
  if (directory.length === 0 || directory === ".") return ".";
  return directory;
}

function relativeOutputPath(from: string, to: string): string {
  const normalizedFrom = from === "." ? "" : from;
  const normalizedTo = to === "." ? "" : to;
  const path = normalizeWorkspacePath(relative(normalizedFrom, normalizedTo));
  return path.length === 0 ? "." : path;
}

function normalizeWorkspacePath(path: string): string {
  return path.replaceAll("\\", "/").replace(/^\.\//, "");
}

function lockItemForRule(args: {
  readonly consumers?: readonly OutputConsumer[];
  readonly files: readonly RenderedFile[];
  readonly graph: BuildGraph;
  readonly name: string;
  readonly owner?: OutputOwner;
  readonly outputPath: string;
  readonly outputRoot: string;
  readonly preprocessDependencies: readonly string[];
  readonly sourceHash: string;
  readonly sourceOrigin?: SourceOrigin;
  readonly sourcePath: string;
  readonly transforms?: readonly AppliedTransform[];
}): LockItem {
  return {
    ...(args.consumers === undefined ? {} : { consumers: args.consumers }),
    fileModes: renderedFileModes(args.outputRoot, args.files),
    files: args.files
      .map((file) => normalizeManagedRelativePath(relative(args.outputRoot, file.path)))
      .sort(),
    kind: "rule",
    name: args.name,
    outputHash: hashRenderedFiles(args.outputRoot, args.files),
    outputPath: normalizeManagedRelativePath(
      relative(args.outputRoot, args.outputPath)
    ),
    ...(args.owner === undefined ? {} : { owner: args.owner }),
    role:
      args.owner !== undefined && "standardProfile" in args.owner
        ? "standard"
        : "bundle",
    ...(args.preprocessDependencies.length === 0
      ? {}
      : { preprocessDependencies: args.preprocessDependencies }),
    sourceHash: args.sourceHash,
    ...(args.sourceOrigin === undefined
      ? {}
      : { sourceOrigin: args.sourceOrigin }),
    sourcePath: args.sourcePath,
    ...(args.transforms === undefined || args.transforms.length === 0
      ? {}
      : { transforms: args.transforms }),
    version: rootVersion(args.graph),
  };
}

function hashTextRule(
  rule: SourceRule,
  preprocessDependencies: readonly string[],
  rootPath: string
): string {
  return hashRules([rule], preprocessDependencies, rootPath);
}

function hashRules(
  rules: readonly SourceRule[],
  preprocessDependencies: readonly string[],
  rootPath: string
): string {
  const hash = createHash("sha256");
  hash.update("skillset-rule-source-v1\0");
  for (const rule of [...rules].sort((left, right) =>
    compareStrings(left.sourcePath, right.sourcePath)
  )) {
    hash.update(rule.relativePath);
    hash.update("\0");
    hash.update(stringifyJson(rule.frontmatter));
    hash.update("\0");
    hash.update(rule.body);
    hash.update("\0");
  }
  for (const dependency of preprocessDependencies) {
    hash.update("preprocess-dependency\0");
    hash.update(dependency);
    hash.update("\0");
    hash.update(readPreprocessDependencySync(rootPath, dependency));
    hash.update("\0");
  }
  return `sha256:${hash.digest("hex")}`;
}

interface TranslatedBody {
  readonly text: string;
  readonly transforms: readonly AppliedTransform[];
}

interface RenderedRuleMarkdown {
  readonly content: string;
  readonly preprocessDependencies: readonly string[];
  readonly transforms?: readonly AppliedTransform[];
}

function translateClaudeDialect(body: string): TranslatedBody {
  const matches = recognizeTransforms(body, "claude");
  const counts = new Map<string, number>();
  let text = body;
  for (const match of [...matches].reverse()) {
    const rendered = lowerTransform(match, "codex");
    if (rendered === undefined) continue;
    text = `${text.slice(0, match.index)}${rendered}${text.slice(match.index + match.text.length)}`;
    counts.set(match.intent, (counts.get(match.intent) ?? 0) + 1);
  }
  const transforms = [...counts.entries()]
    .sort(([left], [right]) => compareStrings(left, right))
    .map(([intent, count]) => ({ count, intent }));
  return { text, transforms };
}

function formattedPreprocessDependencies(
  graph: BuildGraph,
  dependencies: ReadonlySet<string>
): readonly string[] {
  return [...dependencies]
    .map((dependency) => formatPreprocessDependency(graph.rootPath, dependency))
    .sort(compareStrings);
}

function targetProjectRoot(graph: BuildGraph, target: TargetName): string {
  const configured = readString(
    graph.root.targets[target].options,
    "projectRoot"
  );
  if (configured !== undefined) return configured;
  return targetDescriptor(target).projectRoot;
}

function hashRenderedFiles(
  outputRoot: string,
  files: readonly RenderedFile[]
): string {
  const hash = createHash("sha256");
  hash.update("skillset-output-v2\0");
  for (const file of [...files].sort((left, right) =>
    compareStrings(left.path, right.path)
  )) {
    hash.update(normalizeManagedRelativePath(relative(outputRoot, file.path)));
    hash.update("\0");
    hash.update(file.mode.toString(8).padStart(4, "0"));
    hash.update("\0");
    hash.update(file.content);
    hash.update("\0");
  }
  return `sha256:${hash.digest("hex")}`;
}
